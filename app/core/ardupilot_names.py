def servo_function_name(value) -> str:
    """Name for a SERVOn_FUNCTION value, or '' when unset/unknown."""
    try:
        v = int(value)
    except (TypeError, ValueError):
        return ''
    if v <= 0:
        return ''
    return SERVO_FUNCTIONS.get(v, 'Function %d' % v)


def rc_option_name(value) -> str:
    """Name for an RCn_OPTION value, or '' when the channel has no option."""
    try:
        v = int(value)
    except (TypeError, ValueError):
        return ''
    if v <= 0:
        return ''
    return RC_OPTIONS.get(v, 'Option %d' % v)
